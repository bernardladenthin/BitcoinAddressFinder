package net.ladenthin.bitcoinaddressfinder.statistics;

import java.math.BigDecimal;
import java.math.MathContext;
import java.math.RoundingMode;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Collectors;

/**
 * Builds the human-readable statistics line printed by the consumer.
 */
public class Statistics {

    /** Creates a new {@link Statistics}. */
    public Statistics() {}

    /** Number of milliseconds per second. */
    @Deprecated
    public static final int ONE_SECOND_IN_MILLISECONDS = 1000;

    /**
     * Builds the periodic human-readable statistics line logged by the consumer.
     *
     * <p>The {@code Checked … keys} figure is the lifetime total; the keys/second and keys/minute
     * figures are the <em>current windowed</em> throughput (averaged over
     * {@code rateWindowSeconds}), not a lifetime average, so they track warm-up and thermal
     * throttling rather than settling to a long-run mean.
     *
     * @param uptime                       elapsed run time in milliseconds (lifetime)
     * @param keys                         total number of hash160 lookups against LMDB so far
     *                                     (lifetime) — i.e. candidates that survived any GPU
     *                                     pre-filter and reached the consumer
     * @param windowKeysPerSecond          current LMDB-lookup throughput in keys/second, averaged
     *                                     over the trailing {@code rateWindowSeconds} window
     * @param generatedKeys                total candidate keys generated by the producers so far
     *                                     (lifetime) — what enters the pipeline at the top, before
     *                                     any GPU pre-filter
     * @param windowGeneratedPerSecond     current candidate-generation throughput in keys/second,
     *                                     averaged over the same trailing window
     * @param rateWindowSeconds            the trailing window (seconds) the rate is averaged over
     * @param keysSumOfTimeToCheckContains cumulative time (ns) spent in presence lookups
     * @param generatedKeysByProducer      generated-candidate counts keyed by producer label
     *                                     ({@code "<keyProducerId> (<Strategy>, <CPU|GPU>)"}); lets
     *                                     concurrently running producers be told apart, and be
     *                                     compared against each other — see
     *                                     {@link #describeProducerShares(Map)}
     * @param producersRunning             number of producers currently in the RUNNING state
     * @param consumersRunning             number of consumer worker threads currently running
     * @param consumerReady               number of consume cycles the consumer was ready for work
     *                                     (empty queue, nothing to do); rising is normal/healthy — the
     *                                     CPU keeps up and an empty queue is the desired state
     * @param producerBlocked              number of times a producer hit a full queue on enqueue;
     *                                     rising is the warning sign — the consumer/CPU is too slow (CPU-bound)
     * @param keysQueueSize                current number of batches waiting in the queue
     * @param hits                         total number of address hits found so far
     * @return the formatted statistics message
     */
    public String createStatisticsMessage(
            long uptime,
            long keys,
            double windowKeysPerSecond,
            long generatedKeys,
            double windowGeneratedPerSecond,
            long rateWindowSeconds,
            long keysSumOfTimeToCheckContains,
            Map<String, Long> generatedKeysByProducer,
            long producersRunning,
            long consumersRunning,
            long consumerReady,
            long producerBlocked,
            long keysQueueSize,
            long hits) {
        // calculate uptime (lifetime)
        long uptimeInSeconds = uptime / (long) ONE_SECOND_IN_MILLISECONDS;
        long uptimeInMinutes = uptimeInSeconds / 60;
        // calculate average contains time
        long averageContainsTime = keysSumOfTimeToCheckContains / Math.max(keys, 1);
        String producerShares = describeProducerShares(generatedKeysByProducer);

        // The two ends of the pipeline, side by side:
        //   Generated  = candidates the producers create (the GPU's real output rate).
        //   -> LMDB     = hash160 lookups that survive the GPU pre-filter and hit the consumer/LMDB.
        // The prominent rate used to be only the second one, which for a GPU-filtered run is a tiny
        // fraction of the actual work and made the tool look idle. Both are shown now, plus how much
        // the pre-filter removed before LMDB.
        String pruned = describeFilterEffect(windowGeneratedPerSecond, windowKeysPerSecond);

        return "Statistics: [uptime " + uptimeInMinutes + " min] [Generated "
                + formatRate(windowGeneratedPerSecond) + " (" + (generatedKeys / 1_000_000L) + " M total)] [-> LMDB "
                + formatRate(windowKeysPerSecond) + " (" + (keys / 1_000_000L) + " M lookups total)" + pruned
                + "] [rate window " + rateWindowSeconds + "s] [Keys per producer: " + producerShares
                + "] [Producers running: " + producersRunning + "] [Consumers running: " + consumersRunning
                + "] [Consumer ready for work (queue empty): " + consumerReady
                + "] [Producer blocked (queue full): " + producerBlocked + "] [Average contains time: "
                + averageContainsTime + " ns] [keys queue size: " + keysQueueSize + "] [Hits: " + hits + "]";
    }

    /**
     * Significant digits kept by {@link #formatRate(double)} and {@link #formatCount(long)}.
     *
     * <p>Both used to round the scaled value to a whole number, which made the printed precision
     * depend on where in a decade the value happened to fall: {@code 1_400_000_000} and
     * {@code 1_000_000_000} both rendered as {@code "1 G/s"}, a 40 % spread collapsed into one
     * bucket, while a value just below the next threshold kept three digits. Tuning runs compare
     * throughput numbers against each other, so a scale whose resolution drops to ~50 % exactly at a
     * unit boundary hides the difference the comparison is trying to measure. Reported from the
     * field for the {@code G/s} boundary, but the same collapse happened at {@code k/s} and
     * {@code M/s}.
     */
    private static final int SIGNIFICANT_DIGITS = 4;

    /**
     * Formats a per-second rate, auto-scaling to k/s, M/s or G/s so the number stays readable across
     * the whole range (a starved consumer at a few thousand/s up to a GPU in the G/s).
     *
     * <p>The unit is chosen on the value as it will be displayed: a rate that rounds up to a thousand
     * of its unit is shown in the next one ({@code 999_999.9} &#x2192; {@code "1.000 M/s"}, not
     * {@code "1000.0 k/s"}). See {@link #roundForDisplay(double)}.
     *
     * @param perSecond the rate in units per second
     * @return e.g. {@code "1.400 G/s"}, {@code "130.0 M/s"}, {@code "2.013 k/s"} or {@code "412/s"}
     */
    static String formatRate(double perSecond) {
        return formatScaled(perSecond, "/s");
    }

    /**
     * Scales {@code value} into G, M or k, chosen on {@link #roundForDisplay(double)} of the value so
     * the rounding cannot carry it to a thousand of a unit, and renders it with
     * {@link #withSignificantDigits(double)}; below a thousand it is rendered as a whole number.
     *
     * @param value  the value to format
     * @param suffix appended after the unit, e.g. {@code "/s"} for a rate or {@code ""} for a count
     * @return the scaled value with its unit and suffix
     */
    private static String formatScaled(double value, String suffix) {
        double rounded = roundForDisplay(value);
        if (rounded >= 1_000_000_000.0d) {
            return withSignificantDigits(rounded / 1_000_000_000.0d) + " G" + suffix;
        }
        if (rounded >= 1_000_000.0d) {
            return withSignificantDigits(rounded / 1_000_000.0d) + " M" + suffix;
        }
        if (rounded >= 1_000.0d) {
            return withSignificantDigits(rounded / 1_000.0d) + " k" + suffix;
        }
        return Math.round(value) + suffix;
    }

    /**
     * Rounds {@code value} to the precision it is displayed with, before the unit is chosen: to its
     * integer digits below a thousand (a whole number, where no unit is shown and no decimals either),
     * and to {@link #SIGNIFICANT_DIGITS} significant digits from a thousand on, where the value has
     * at least four. Choosing the unit on the unrounded value let {@code 999_999.9} pick k and then
     * round to {@code "1000.0 k/s"}.
     *
     * <p>One rounding with a computed precision rather than a branch at a thousand: both branches
     * agreed at exactly a thousand, so the boundary of that comparison could not be observed, and a
     * mutation test cannot tell {@code <} from {@code <=} there.
     *
     * <p>A value that is not finite is returned unchanged; {@link #formatScaled} renders it as before
     * (a {@code NaN} rate as {@code "0/s"}, an infinite one as {@code "Infinity G/s"}). A negative or
     * fractional value rounds to one digit at
     * least, which {@link #formatScaled} never shows: below a thousand it renders the whole number of
     * the original value.
     *
     * @param value the value to round
     * @return the value rounded to its displayed precision
     */
    private static double roundForDisplay(double value) {
        if (!Double.isFinite(value)) {
            return value;
        }
        int precision = Math.max(1, Math.min(SIGNIFICANT_DIGITS, integerDigits(value)));
        return BigDecimal.valueOf(value)
                .round(new MathContext(precision, RoundingMode.HALF_UP))
                .doubleValue();
    }

    /**
     * The number of digits before the decimal point of a positive value ({@code 999.5} has three,
     * {@code 1000} four); zero or less for a value below one, and one for a value that is not positive
     * ({@code log10} of zero or a negative number has no integer part to count).
     *
     * @param value the value
     * @return its integer digits
     */
    private static int integerDigits(double value) {
        return (int) Math.floor(Math.log10(value)) + 1;
    }

    /**
     * Renders a value that has already been divided into its unit — so it lies in {@code [1, 1000)} —
     * with as many decimals as it takes to reach {@link #SIGNIFICANT_DIGITS}.
     *
     * <p>The value has already been rounded to {@link #SIGNIFICANT_DIGITS} by
     * {@link #roundForDisplay(double)} and its unit chosen on that, so it never renders as
     * {@code "1000.0"}; only above the largest unit (a thousand G or more) does it have four integer
     * digits.
     *
     * @param scaled the value in its unit, in {@code [1, 1000)}
     * @return the value rendered with a constant number of significant digits
     */
    private static String withSignificantDigits(double scaled) {
        int decimals = Math.max(0, SIGNIFICANT_DIGITS - integerDigits(scaled));
        // A literal format string per branch, rather than one assembled from `decimals` or looked up
        // in an array. Both of those are still "computed" to a static analyser even when every input
        // is our own arithmetic, and spelling the three cases out documents the only shapes this
        // produces: a value scaled into its unit lies in [1, 1000), so it has one to three integer
        // digits.
        return switch (decimals) {
            case 0 -> String.format(Locale.ROOT, "%.0f", scaled);
            case 1 -> String.format(Locale.ROOT, "%.1f", scaled);
            case 2 -> String.format(Locale.ROOT, "%.2f", scaled);
            default -> String.format(Locale.ROOT, "%.3f", scaled);
        };
    }

    /**
     * Renders the per-producer breakdown as {@code "label=<count> (<share>%), label=<count>
     * (<share>%)"}, or {@code "none"} while no producer has generated anything yet.
     *
     * <p>Counts candidates rather than dispatched batches, and states each producer's share of the
     * total, because the batch count this group used to print is not comparable between producers:
     * a batch yields {@code 2^batchSizeInBits} candidates, so two GPUs configured at 24 and 21 bits
     * differ 8× per batch. A run whose batch counts read {@code 1156} vs {@code 595} — an apparent
     * 2:1 split — can in fact be a 20:1 split of the actual work, which is precisely the question
     * the group exists to answer when more than one device is configured.
     *
     * @param generatedKeysByProducer generated-candidate counts keyed by producer label; iteration
     *                                order is the caller's (sorted, for a stable line)
     * @return the rendered breakdown, or {@code "none"} when the map is empty
     */
    static String describeProducerShares(Map<String, Long> generatedKeysByProducer) {
        if (generatedKeysByProducer.isEmpty()) {
            return "none";
        }
        long total = generatedKeysByProducer.values().stream()
                .mapToLong(Long::longValue)
                .sum();
        return generatedKeysByProducer.entrySet().stream()
                .map(entry ->
                        entry.getKey() + "=" + formatCount(entry.getValue()) + describeShare(entry.getValue(), total))
                .collect(Collectors.joining(", "));
    }

    /**
     * Formats one producer's share of the generated total.
     *
     * @param generated this producer's candidate count
     * @param total     the candidate count across all producers
     * @return {@code " (NN.N%)"}, or an empty string when the total is zero (every producer is
     *         registered but none has generated anything yet, so no share is meaningful)
     */
    private static String describeShare(long generated, long total) {
        if (total <= 0L) {
            return "";
        }
        return String.format(Locale.ROOT, " (%.1f%%)", generated * 100.0d / total);
    }

    /**
     * Formats an absolute count, auto-scaling to k, M or G on the same thresholds as
     * {@link #formatRate(double)} so the two read consistently within one line, including the carry
     * into the next unit ({@code 999_999_999} &#x2192; {@code "1.000 G"}).
     *
     * @param count the count to format
     * @return e.g. {@code "19.39 G"}, {@code "130.0 M"}, {@code "3.000 k"} or {@code "412"}
     */
    static String formatCount(long count) {
        // The display keeps four significant digits, far fewer than a double carries.
        return formatScaled((double) count, "");
    }

    /**
     * Describes how much the GPU pre-filter removed before LMDB, as the share of the potential
     * hash160 lookups (two per generated candidate) that never reached the consumer.
     *
     * @param generatedPerSecond candidate-generation rate
     * @param lookupsPerSecond    LMDB-lookup rate (post-filter)
     * @return {@code ", NN.N% pre-filtered"}, or an empty string when there is not yet enough data
     */
    private static String describeFilterEffect(double generatedPerSecond, double lookupsPerSecond) {
        double potentialLookups = generatedPerSecond * 2.0; // compressed + uncompressed per candidate
        // Report only once candidates are generated and some (but not all) survive to LMDB. The
        // second test also covers the no-generation case (potentialLookups == 0, so any lookup rate
        // is >= it) and the full-transfer case (lookups reach the full potential, nothing filtered),
        // and it keeps the division safe: it runs only when 0 < lookupsPerSecond < potentialLookups.
        if (lookupsPerSecond <= 0.0 || lookupsPerSecond >= potentialLookups) {
            return "";
        }
        double prunedPercent = (1.0 - lookupsPerSecond / potentialLookups) * 100.0;
        return String.format(Locale.ROOT, ", %.2f%% pre-filtered", prunedPercent);
    }
}
